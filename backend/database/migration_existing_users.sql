-- ==========================================================
-- Safe Migration: Convert public.users.id to Sequential BIGINT (1, 2, 3...)
-- Preserving All Existing User Records
-- ==========================================================

BEGIN;

-- 1. Remove foreign keys pointing to old UUID primary key
ALTER TABLE IF EXISTS public.health_profiles DROP CONSTRAINT IF EXISTS health_profiles_user_id_fkey;
ALTER TABLE IF EXISTS public.favorites DROP CONSTRAINT IF EXISTS favorites_user_id_fkey;
ALTER TABLE IF EXISTS public.water_tracking DROP CONSTRAINT IF EXISTS water_tracking_user_id_fkey;
ALTER TABLE IF EXISTS public.fitness_tracking DROP CONSTRAINT IF EXISTS fitness_tracking_user_id_fkey;
ALTER TABLE IF EXISTS public.meal_plans DROP CONSTRAINT IF EXISTS meal_plans_user_id_fkey;
ALTER TABLE IF EXISTS public.recommendation_history DROP CONSTRAINT IF EXISTS recommendation_history_user_id_fkey;

-- 2. Remove old user_id column if present
ALTER TABLE public.users DROP COLUMN IF EXISTS user_id;

-- 3. Remove the old primary key constraint (with CASCADE)
ALTER TABLE public.users DROP CONSTRAINT IF EXISTS users_pkey CASCADE;

-- 4. Temporarily rename the old UUID id
ALTER TABLE public.users RENAME COLUMN id TO old_uuid_id;

-- 5. Create the new numeric auto-incrementing id
ALTER TABLE public.users ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY;

-- 6. Give existing users sequential numbers 1, 2, 3...
WITH numbered AS (
    SELECT
        old_uuid_id,
        ROW_NUMBER() OVER (
            ORDER BY created_at, old_uuid_id
        ) AS new_number
    FROM public.users
)
UPDATE public.users u
SET id = numbered.new_number
FROM numbered
WHERE u.old_uuid_id = numbered.old_uuid_id;

-- 7. Set the auto-increment sequence to continue after the existing max ID
SELECT setval(
    pg_get_serial_sequence('public.users', 'id'),
    COALESCE((SELECT MAX(id) FROM public.users), 1),
    true
);

-- 8. Remove the old UUID id column
ALTER TABLE public.users DROP COLUMN old_uuid_id;

-- 9. Make the new numeric id the primary key
ALTER TABLE public.users ADD CONSTRAINT users_pkey PRIMARY KEY (id);

-- 10. Update dependent tables user_id to BIGINT if they were UUID
ALTER TABLE IF EXISTS public.health_profiles ALTER COLUMN user_id TYPE BIGINT USING NULL;
ALTER TABLE IF EXISTS public.favorites ALTER COLUMN user_id TYPE BIGINT USING NULL;
ALTER TABLE IF EXISTS public.water_tracking ALTER COLUMN user_id TYPE BIGINT USING NULL;
ALTER TABLE IF EXISTS public.fitness_tracking ALTER COLUMN user_id TYPE BIGINT USING NULL;
ALTER TABLE IF EXISTS public.meal_plans ALTER COLUMN user_id TYPE BIGINT USING NULL;
ALTER TABLE IF EXISTS public.recommendation_history ALTER COLUMN user_id TYPE BIGINT USING NULL;

-- 11. Re-add foreign key constraints pointing to the new numeric BIGINT id
ALTER TABLE IF EXISTS public.health_profiles 
    ADD CONSTRAINT health_profiles_user_id_fkey 
    FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE;

ALTER TABLE IF EXISTS public.favorites 
    ADD CONSTRAINT favorites_user_id_fkey 
    FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE;

ALTER TABLE IF EXISTS public.water_tracking 
    ADD CONSTRAINT water_tracking_user_id_fkey 
    FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE;

ALTER TABLE IF EXISTS public.fitness_tracking 
    ADD CONSTRAINT fitness_tracking_user_id_fkey 
    FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE;

ALTER TABLE IF EXISTS public.meal_plans 
    ADD CONSTRAINT meal_plans_user_id_fkey 
    FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE;

ALTER TABLE IF EXISTS public.recommendation_history 
    ADD CONSTRAINT recommendation_history_user_id_fkey 
    FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE;

COMMIT;

-- Check the final result
