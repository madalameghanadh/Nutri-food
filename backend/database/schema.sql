-- ==========================================================
-- NutriRoute Database Schema for Supabase PostgreSQL
-- ==========================================================

-- Enable UUID extension if needed
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. USERS TABLE (Sequential Auto-Incrementing ID: 1, 2, 3, 4, 5...)
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_user_id UUID UNIQUE NOT NULL,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) UNIQUE NOT NULL,
    phone VARCHAR(20),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. HEALTH PROFILES TABLE
CREATE TABLE IF NOT EXISTS public.health_profiles (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id BIGINT UNIQUE NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    age INT NOT NULL DEFAULT 25,
    gender VARCHAR(20) DEFAULT 'other',
    height NUMERIC(5, 2) NOT NULL DEFAULT 170.0,
    weight NUMERIC(5, 2) NOT NULL DEFAULT 65.0,
    bmi NUMERIC(4, 2) NOT NULL DEFAULT 22.5,
    bmi_category VARCHAR(50) DEFAULT 'Normal range',
    activity_level VARCHAR(50) DEFAULT 'Moderately Active',
    diet_preference VARCHAR(50) DEFAULT 'Vegetarian',
    allergies TEXT[] DEFAULT '{}',
    health_conditions TEXT[] DEFAULT '{}',
    daily_calorie_target INT DEFAULT 2000,
    water_target INT DEFAULT 8,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. FOODS TABLE
CREATE TABLE IF NOT EXISTS public.foods (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    name VARCHAR(150) UNIQUE NOT NULL,
    category VARCHAR(50) NOT NULL,
    description TEXT,
    price NUMERIC(6, 2) NOT NULL DEFAULT 150.00,
    calories INT NOT NULL,
    protein NUMERIC(5, 2) NOT NULL DEFAULT 0,
    carbohydrates NUMERIC(5, 2) NOT NULL DEFAULT 0,
    fat NUMERIC(5, 2) NOT NULL DEFAULT 0,
    fiber NUMERIC(5, 2) DEFAULT 0,
    sugar NUMERIC(5, 2) DEFAULT 0,
    serving_size VARCHAR(50) DEFAULT '1 serving',
    diet_type VARCHAR(50) DEFAULT 'Vegetarian',
    allergens TEXT[] DEFAULT '{}',
    health_benefits TEXT[] DEFAULT '{}',
    image TEXT,
    tags TEXT[] DEFAULT '{}',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. FAVORITES TABLE
CREATE TABLE IF NOT EXISTS public.favorites (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    food_id UUID NOT NULL REFERENCES public.foods(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    CONSTRAINT unique_user_favorite UNIQUE (user_id, food_id)
);

-- 5. WATER TRACKING TABLE
CREATE TABLE IF NOT EXISTS public.water_tracking (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    tracking_date DATE NOT NULL DEFAULT CURRENT_DATE,
    glasses INT NOT NULL DEFAULT 0,
    target INT NOT NULL DEFAULT 8,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    CONSTRAINT unique_user_water_date UNIQUE (user_id, tracking_date)
);

-- 6. FITNESS TRACKING TABLE
CREATE TABLE IF NOT EXISTS public.fitness_tracking (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    tracking_date DATE NOT NULL DEFAULT CURRENT_DATE,
    steps INT NOT NULL DEFAULT 0,
    exercise_minutes INT NOT NULL DEFAULT 0,
    calories_burned INT NOT NULL DEFAULT 0,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    CONSTRAINT unique_user_fitness_date UNIQUE (user_id, tracking_date)
);

-- 7. MEAL PLANS TABLE
CREATE TABLE IF NOT EXISTS public.meal_plans (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    plan_date DATE NOT NULL DEFAULT CURRENT_DATE,
    breakfast JSONB DEFAULT '[]'::jsonb,
    lunch JSONB DEFAULT '[]'::jsonb,
    snack JSONB DEFAULT '[]'::jsonb,
    dinner JSONB DEFAULT '[]'::jsonb,
    total_calories INT DEFAULT 0,
    total_protein NUMERIC(6, 2) DEFAULT 0,
    total_carbohydrates NUMERIC(6, 2) DEFAULT 0,
    total_fat NUMERIC(6, 2) DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    CONSTRAINT unique_user_meal_date UNIQUE (user_id, plan_date)
);

-- 8. RECOMMENDATION HISTORY TABLE
CREATE TABLE IF NOT EXISTS public.recommendation_history (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    food_id UUID NOT NULL REFERENCES public.foods(id) ON DELETE CASCADE,
    score INT NOT NULL,
    reason TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 9. ORDERS TABLE (Delivery System)
CREATE TABLE IF NOT EXISTS public.orders (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    order_number VARCHAR(30) UNIQUE NOT NULL,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    items JSONB NOT NULL DEFAULT '[]'::jsonb,
    total_amount NUMERIC(8, 2) NOT NULL DEFAULT 0.00,
    delivery_fee NUMERIC(6, 2) NOT NULL DEFAULT 40.00,
    total_calories INT DEFAULT 0,
    delivery_address TEXT NOT NULL,
    contact_phone VARCHAR(20) NOT NULL,
    delivery_notes TEXT,
    payment_method VARCHAR(50) DEFAULT 'Cash on Delivery',
    payment_status VARCHAR(50) DEFAULT 'Pending',
    order_status VARCHAR(50) DEFAULT 'Preparing',
    rider_name VARCHAR(100) DEFAULT 'Suresh Kumar',
    rider_phone VARCHAR(20) DEFAULT '+91 98450 12345',
    rider_lat NUMERIC(9, 6) DEFAULT 12.9716,
    rider_lng NUMERIC(9, 6) DEFAULT 77.5946,
    estimated_delivery_minutes INT DEFAULT 30,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

