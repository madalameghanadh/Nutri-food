-- ====================================================================
-- NutriRoute Database Migration: Sequential Auto-Incrementing User ID
-- ====================================================================
-- This migration converts `public.users.id` from UUID to an auto-incrementing
-- sequential BIGINT (1, 2, 3, 4, 5...) while preserving `auth_user_id` (UUID)
-- for Supabase Authentication linking.
-- ====================================================================

-- 1. Drop existing foreign key constraints pointing to public.users(id)
ALTER TABLE IF EXISTS public.health_profiles DROP CONSTRAINT IF EXISTS health_profiles_user_id_fkey;
ALTER TABLE IF EXISTS public.favorites DROP CONSTRAINT IF EXISTS favorites_user_id_fkey;
ALTER TABLE IF EXISTS public.water_tracking DROP CONSTRAINT IF EXISTS water_tracking_user_id_fkey;
ALTER TABLE IF EXISTS public.fitness_tracking DROP CONSTRAINT IF EXISTS fitness_tracking_user_id_fkey;
ALTER TABLE IF EXISTS public.meal_plans DROP CONSTRAINT IF EXISTS meal_plans_user_id_fkey;
ALTER TABLE IF EXISTS public.recommendation_history DROP CONSTRAINT IF EXISTS recommendation_history_user_id_fkey;

-- 2. Drop dependent child tables temporarily if migrating fresh, or alter column types
DROP TABLE IF EXISTS public.health_profiles CASCADE;
DROP TABLE IF EXISTS public.favorites CASCADE;
DROP TABLE IF EXISTS public.water_tracking CASCADE;
DROP TABLE IF EXISTS public.fitness_tracking CASCADE;
DROP TABLE IF EXISTS public.meal_plans CASCADE;
DROP TABLE IF EXISTS public.recommendation_history CASCADE;
DROP TABLE IF EXISTS public.users CASCADE;

-- 3. Recreate public.users with Auto-Incrementing BIGINT id (1, 2, 3...)
CREATE TABLE public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_user_id UUID UNIQUE NOT NULL,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) UNIQUE NOT NULL,
    phone VARCHAR(20),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. Recreate dependent tables with BIGINT user_id foreign key
CREATE TABLE public.health_profiles (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id BIGINT UNIQUE NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    age INT NOT NULL DEFAULT 25,
    gender VARCHAR(20) DEFAULT 'other',
    height NUMERIC(5, 2) NOT NULL DEFAULT 170.0,
    weight NUMERIC(5, 2) NOT NULL DEFAULT 65.0,
    bmi NUMERIC(4, 2) NOT NULL DEFAULT 22.5,
    bmi_category VARCHAR(50) DEFAULT 'Normal range',
    activity_level VARCHAR(50) DEFAULT 'Moderately Active',
    diet_preference VARCHAR(50) DEFAULT 'Vegetarian',
    allergies TEXT[] DEFAULT '{}',
    health_conditions TEXT[] DEFAULT '{}',
    daily_calorie_target INT DEFAULT 2000,
    water_target INT DEFAULT 8,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE public.favorites (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    food_id UUID NOT NULL REFERENCES public.foods(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    CONSTRAINT unique_user_favorite UNIQUE (user_id, food_id)
);

CREATE TABLE public.water_tracking (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    tracking_date DATE NOT NULL DEFAULT CURRENT_DATE,
    glasses INT NOT NULL DEFAULT 0,
    target INT NOT NULL DEFAULT 8,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    CONSTRAINT unique_user_water_date UNIQUE (user_id, tracking_date)
);

CREATE TABLE public.fitness_tracking (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    tracking_date DATE NOT NULL DEFAULT CURRENT_DATE,
    steps INT NOT NULL DEFAULT 0,
    exercise_minutes INT NOT NULL DEFAULT 0,
    calories_burned INT NOT NULL DEFAULT 0,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    CONSTRAINT unique_user_fitness_date UNIQUE (user_id, tracking_date)
);

CREATE TABLE public.meal_plans (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    plan_date DATE NOT NULL DEFAULT CURRENT_DATE,
    breakfast JSONB DEFAULT '[]'::jsonb,
    lunch JSONB DEFAULT '[]'::jsonb,
    snack JSONB DEFAULT '[]'::jsonb,
    dinner JSONB DEFAULT '[]'::jsonb,
    total_calories INT DEFAULT 0,
    total_protein NUMERIC(6, 2) DEFAULT 0,
    total_carbohydrates NUMERIC(6, 2) DEFAULT 0,
    total_fat NUMERIC(6, 2) DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    CONSTRAINT unique_user_meal_date UNIQUE (user_id, plan_date)
);

CREATE TABLE public.recommendation_history (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    food_id UUID NOT NULL REFERENCES public.foods(id) ON DELETE CASCADE,
    score INT NOT NULL,
    reason TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 5. Indexes
CREATE INDEX IF NOT EXISTS idx_users_auth ON public.users(auth_user_id);
CREATE INDEX IF NOT EXISTS idx_health_user ON public.health_profiles(user_id);
CREATE INDEX IF NOT EXISTS idx_favorites_user ON public.favorites(user_id);
CREATE INDEX IF NOT EXISTS idx_water_user_date ON public.water_tracking(user_id, tracking_date);
CREATE INDEX IF NOT EXISTS idx_fitness_user_date ON public.fitness_tracking(user_id, tracking_date);
CREATE INDEX IF NOT EXISTS idx_meals_user_date ON public.meal_plans(user_id, plan_date);
CREATE INDEX IF NOT EXISTS idx_history_user ON public.recommendation_history(user_id);

